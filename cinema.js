function escapeHtml(s) {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

function render(tabId) {
  const items = data[tabId] || [];
  if (!items.length) {
    grid.innerHTML = "";
    empty.hidden = false;
    return;
  }
  empty.hidden = true;
  grid.innerHTML = items
    .map(
      (it) => `
      <a class="movie-card" href="#" data-id="${it.id}">
        <img src="${it.cover}" referrerpolicy="no-referrer" alt="" loading="lazy"
             onerror="this.parentElement.classList.add('no-thumb'); this.remove();" />
        <strong>${escapeHtml(it.title)}</strong><span>Chơi:${it.count}</span>
      </a>`
    )
    .join("");
}

tabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    tabs.forEach((t) => t.classList.toggle("is-active", t === tab));
    render(tab.dataset.tab);
    document.querySelector(".cinema-scroll")?.scrollTo({ top: 0 });
  });
});

// Try to fetch fresh data from Supabase, fallback to hardcoded if empty/error
async function tryLoadFromDB() {
  if (!window.sb) return;
  try {
    const { data, error } = await window.sb
      .from("videos")
      .select("external_id, category_id, title, cover, play_count")
      .order("play_count", { ascending: false })
      .limit(500);
    if (error || !data?.length) return;

    const byCat = { "1": [], "2": [], "3": [] };
    for (const v of data) {
      const item = { id: v.external_id || v.id, title: v.title, count: v.play_count, cover: v.cover };
      if (byCat[String(v.category_id)]) byCat[String(v.category_id)].push(item);
    }
    if (byCat["1"].length) data["1"] = byCat["1"];
    if (byCat["2"].length) data["2"] = byCat["2"];

    // Refresh derived tabs
    const tab1 = data["1"];
    if (tab1?.length) {
      data["2"] = (data["2"] || []).concat([...tab1].sort((a, b) => b.id - a.id).slice(0, 60));
      data["3"] = [...tab1].sort((a, b) => b.count - a.count).slice(0, 60);
    }
    const active = document.querySelector(".cinema-tab.is-active");
    render(active?.dataset.tab || "1");
  } catch (e) {
    console.warn("[cinema] DB fetch failed, using hardcoded:", e);
  }
}

